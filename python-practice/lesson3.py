# 第三课：AI 女友 V1 第 1 步——"复读机女友"
# 今天的她笨笨的，只会说一句话。但这是你的 AI 女友项目的第一块砖！
# 下面的零件你都学过，不需要学任何新东西。

while True:                        # ① 一直陪你聊（猜数字里的老朋友）
    msg = input("你对她说: ")       # ② 你说的话，存进 msg 里

    if msg == "bye":               # ③ 如果你说 bye
        print("哼，说走就走！👋")    # ④ 她就生气告别
        break                      # ⑤ 跳出循环，程序结束

    print("嗯嗯，我在听。然后呢？")   # ⑥ 其他时候，她只会傻傻重复这一句
